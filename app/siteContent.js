function isPlainObject(value) {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function mergeContentValue(defaultValue, nextValue) {
  if (Array.isArray(defaultValue)) {
    if (!Array.isArray(nextValue)) return defaultValue;

    return defaultValue.map((item, index) =>
      mergeContentValue(item, nextValue[index])
    );
  }

  if (isPlainObject(defaultValue)) {
    const source = isPlainObject(nextValue) ? nextValue : {};

    return Object.keys(defaultValue).reduce((merged, key) => {
      merged[key] = mergeContentValue(defaultValue[key], source[key]);
      return merged;
    }, {});
  }

  return nextValue === undefined ? defaultValue : nextValue;
}

export function mergeSiteContent(payload) {
  const merged = mergeContentValue(DEFAULT_SITE_CONTENT, payload);
  merged.services.cards = merged.services.cards?.length ? merged.services.cards : merged.products.cards;
  merged.cases.sideCards = merged.cases.sideCards?.length ? merged.cases.sideCards : merged.cases.cards.slice(1);
  return merged;
}
